-- 移除账号归属字段 owner_id。
--
-- 背景：owner_id 原本用于「普通用户只能编辑/删除自己创建的账号」这条规则。
-- 该规则已经取消——普通用户现在对所有账号拥有完整操作权限，只有编辑与
-- 删除按钮对管理员开放。归属校验函数（requireOwnership / CanManageAccount）
-- 的调用点已全部移除，字段因此不再被任何逻辑读取。
--
-- 它唯一残留的作用是让列表接口对「他人账号」脱敏 access_token。脱敏本身
-- 干扰了运维排查：普通用户本就能对这些账号发起测试、重新授权和查看统计，
-- 却看不到凭证内容，反而制造了「我的账号」和「别人的账号」这种并不存在的
-- 区别。
--
-- 迁移可重复执行。

ALTER TABLE accounts DROP COLUMN IF EXISTS owner_id;
